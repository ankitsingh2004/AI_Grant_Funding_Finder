"""
models.py — Pydantic data models used across the application.
"""
from __future__ import annotations
from typing import List, Optional
from pydantic import BaseModel, Field


class StartupProfile(BaseModel):
    """Profile submitted by the user to personalise grant recommendations."""

    name: str = Field(..., description="Startup name")
    domain: str = Field(
        ...,
        description=(
            "Industry domain e.g. HealthTech, EdTech, AgriTech, FinTech, "
            "CleanEnergy, AI/ML, Cybersecurity, DeepTech"
        ),
    )
    stage: str = Field(
        ...,
        description="Startup stage: Idea | Pre-Seed | Seed | Series-A | Growth",
    )
    location: str = Field(..., description="Country or city/state")
    description: str = Field(
        ..., description="One-paragraph description of the startup"
    )
    team_size: Optional[int] = Field(None, description="Number of employees")
    annual_revenue: Optional[str] = Field(
        None, description="Annual revenue range e.g. <$100K, $100K-$1M"
    )
    website: Optional[str] = Field(None, description="Startup website URL")
    keywords: Optional[List[str]] = Field(
        default_factory=list,
        description="Optional extra keywords to improve matching",
    )


class GrantOpportunity(BaseModel):
    """A single grant or funding opportunity."""

    id: str
    title: str
    source: str
    url: str
    description: str
    eligibility: str
    funding_amount: str
    deadline: str
    domain_tags: List[str] = Field(default_factory=list)
    stage_tags: List[str] = Field(default_factory=list)
    location_tags: List[str] = Field(default_factory=list)
    match_score: float = Field(default=0.0, ge=0.0, le=1.0)
    match_reasons: List[str] = Field(default_factory=list)


class ProposalRequest(BaseModel):
    """Request body for proposal/draft generation."""

    grant: GrantOpportunity
    startup: StartupProfile
    section: str = Field(
        default="full",
        description=(
            "Which section to generate: full | executive_summary | "
            "problem_statement | solution | impact | budget"
        ),
    )


class ProposalResponse(BaseModel):
    """AI-generated proposal draft."""

    section: str
    content: str
    word_count: int
    disclaimer: str = (
        "This draft was generated by IBM Granite AI. "
        "Always review, verify facts, and obtain legal/compliance sign-off "
        "before submitting any official application."
    )


class SearchRequest(BaseModel):
    """Body for the /search endpoint."""

    startup: StartupProfile
    max_results: int = Field(default=10, ge=1, le=50)
    min_match_score: float = Field(default=0.0, ge=0.0, le=1.0)


class SearchResponse(BaseModel):
    """Response from /search endpoint."""

    total_found: int
    grants: List[GrantOpportunity]
    startup_summary: str
